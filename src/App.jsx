// --- Хелперы для перемешивания вопросов и лимита попыток ---
function shuffleArray(array) {
  if (!array || !Array.isArray(array)) return [];
  const arr = [...array];
  for (let i = arr.length - 1; i > 0; i--) {
    const j = Math.floor(Math.random() * (i + 1));
    [arr[i], arr[j]] = [arr[j], arr[i]];
  }
  return arr;
}

function getTestMaxAttempts(test) {
  if (!test) return 0;
  if (typeof test.maxAttempts === 'number') return test.maxAttempts;
  if (test.questions?.[0]?._meta?.maxAttempts !== undefined) {
    return Number(test.questions[0]._meta.maxAttempts);
  }
  if (test.description) {
    const match = test.description.match(/\[attempts:(\d+)\]/i);
    if (match) return Number(match[1]);
  }
  return 0; // 0 = без ограничений
}

function isTestHidden(test) {
  if (!test) return false;
  if (test.hidden === true || test.isHidden === true) return true;
  if (test.questions?.[0]?._meta?.hidden !== undefined) {
    return Boolean(test.questions[0]._meta.hidden);
  }
  if (test.description) {
    if (/\[hidden\]/i.test(test.description) || /\[hidden:true\]/i.test(test.description)) {
      return true;
    }
  }
  return false;
}

function isTheoryBlockHidden(block, hiddenIds = []) {
  if (!block) return false;
  const id = block.id || block.title;
  return Array.isArray(hiddenIds) && hiddenIds.includes(id);
}

function cleanDescription(desc) {
  if (!desc) return '';
  return desc
    .replace(/\[attempts:\d+\]/gi, '')
    .replace(/\[hidden(:true|:false)?\]/gi, '')
    .trim();
}

function prepareShuffledTest(test) {
  if (!test || !test.questions) return test;
  const maxAtt = getTestMaxAttempts(test);
  const shuffledQuestions = shuffleArray(test.questions).map((q) => {
    const originalOptions = q.options || [];
    const correctOptionText = originalOptions[q.correctIndex];
    const shuffledOptions = shuffleArray(originalOptions);
    const newCorrectIndex = shuffledOptions.indexOf(correctOptionText);
    return {
      ...q,
      options: shuffledOptions,
      correctIndex: newCorrectIndex >= 0 ? newCorrectIndex : q.correctIndex
    };
  });
  return {
    ...test,
    maxAttempts: maxAtt,
    questions: shuffledQuestions
  };
}

