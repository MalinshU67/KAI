                          type="button"
                          onClick={handleShowAllTheory}
                          className="px-3.5 py-2 bg-blue-50 hover:bg-blue-100 text-blue-700 text-xs font-semibold rounded-xl border border-blue-200 transition flex items-center gap-1.5 cursor-pointer"
